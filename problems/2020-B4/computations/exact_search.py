#!/usr/bin/env python3
"""Bounded exact evidence for SMMC 2020 B4(b); Python standard library only.

No general construction for the excluded preliminary part is implemented.
`small` searches only the boundary and the first composite/nonprime-power orders.
`filters` reproduces explicitly attributed necessary conditions, not a proof of PPC.
See README.md for normalization arguments, theorem sources, and limitations.
"""

from __future__ import annotations

import argparse
from collections import Counter, deque
from datetime import datetime, timezone
from math import gcd, isqrt
from pathlib import Path
import json
import platform
import time


def factor(n: int) -> dict[int, int]:
    out = {}
    p = 2
    while p * p <= n:
        while n % p == 0:
            out[p] = out.get(p, 0) + 1
            n //= p
        p += 1 if p == 2 else 2
    if n > 1:
        out[n] = out.get(n, 0) + 1
    return out


def verify_difference_set(n: int, d: list[int]) -> dict:
    v = n * n - n + 1
    counts = Counter((a - b) % v for a in d for b in d if a != b)
    valid = (
        len(d) == n
        and len(set(d)) == n
        and all(0 <= a < v for a in d)
        and set(counts) == set(range(1, v))
        and all(c == 1 for c in counts.values())
    )
    return {
        "valid": valid,
        "ordered_difference_count": sum(counts.values()),
        "distinct_nonzero_differences": len(counts),
        "multiplicity_histogram": dict(sorted(Counter(counts.values()).items())),
    }


class LimitReached(Exception):
    pass


def direct_search(n: int, seconds: float, max_nodes: int) -> dict:
    """Enumerate increasing subsets containing 0 and 1; stop at first witness."""
    v = n * n - n + 1
    started = time.monotonic()
    deadline = started + seconds
    nodes = 0

    def visit(d: list[int], used: int) -> list[int] | None:
        nonlocal nodes
        nodes += 1
        if nodes > max_nodes or (nodes % 1024 == 0 and time.monotonic() > deadline):
            raise LimitReached
        if len(d) == n:
            return d
        needed = n - len(d)
        for x in range(d[-1] + 1, v - needed + 1):
            new = 0
            for y in d:
                delta = x - y
                delta = min(delta, v - delta)
                mask = 1 << delta
                if (used | new) & mask:
                    break
                new |= mask
            else:
                result = visit(d + [x], used | new)
                if result is not None:
                    return result
        return None

    try:
        witness = visit([0, 1], 1 << 1)
        status = "witness" if witness is not None else "exhausted_no_witness"
    except LimitReached:
        witness = None
        status = "incomplete_limit_reached"
    result = {
        "n": n,
        "q": n - 1,
        "v": v,
        "status": status,
        "nodes": nodes,
        "seconds_limit": seconds,
        "node_limit": max_nodes,
        "elapsed_seconds": round(time.monotonic() - started, 6),
        "witness": witness,
    }
    if witness is not None:
        result["verification"] = verify_difference_set(n, witness)
        assert result["verification"]["valid"]
    return result


def generated_multipliers(q: int, cap: int | None = None) -> tuple[set[int], bool]:
    """Subgroup generated by prime divisors of q; cap gives a rigorous lower bound."""
    v = q * q + q + 1
    generators = sorted(factor(q))
    assert all(gcd(p, v) == 1 for p in generators)
    seen = {1}
    todo = deque([1])
    while todo:
        a = todo.popleft()
        for p in generators:
            b = a * p % v
            if b not in seen:
                seen.add(b)
                todo.append(b)
                if cap is not None and len(seen) >= cap:
                    return seen, False
    return seen, True


def multiplier_orbits(q: int, group: set[int]) -> list[list[int]]:
    v = q * q + q + 1
    unseen = set(range(v))
    orbits = []
    while unseen:
        x = min(unseen)
        orbit = sorted({x * t % v for t in group})
        unseen.difference_update(orbit)
        orbits.append(orbit)
    return orbits


def basic_exclusion(q: int, factors: dict[int, int]) -> str | None:
    """Conditions ordered only for a disjoint report, not by mathematical strength."""
    if q % 4 in (1, 2) and any(p % 4 == 3 and a % 2 for p, a in factors.items()):
        return "Bruck_Ryser"
    if q % 2 == 0 and q not in (2, 4) and q % 8 != 0:
        return "Jungnickel_Vedder_even_order"
    if q % 3 == 0 and q != 3 and q % 9 != 0:
        return "Wilbrink_three_divisibility"
    if isqrt(q) ** 2 != q:
        for r in factor(q * q + q + 1):
            if any(pow(p, (r - 1) // 2, r) == r - 1 for p in factors):
                return "Mann_quadratic_nonresidue"
    return None


def filters(bound: int) -> dict:
    tally = Counter()
    residual = []
    examples = {}
    for q in range(2, bound + 1):
        f = factor(q)
        if len(f) == 1:
            tally["prime_power_skipped_as_established_context"] += 1
            continue
        reason = basic_exclusion(q, f)
        if reason is None:
            group, complete = generated_multipliers(q, q + 2)
            if not complete or len(group) > q + 1:
                reason = "multiplier_group_size_bound"
            else:
                # For a bounded demonstration only: no explicit orbit pass above q=500.
                # A larger q is retained even if the known published bound excludes it.
                if q <= 500:
                    orbits = multiplier_orbits(q, group)
                    reachable = 1
                    mask = (1 << (q + 2)) - 1
                    for orbit in orbits:
                        reachable |= reachable << len(orbit)
                        reachable &= mask
                    if not ((reachable >> (q + 1)) & 1):
                        reason = "multiplier_orbit_size_subset_sum"
        if reason is None:
            residual.append(q)
            tally["not_excluded_by_implemented_filters"] += 1
        else:
            tally[reason] += 1
            examples.setdefault(reason, q)
    return {
        "q_min": 2,
        "q_max": bound,
        "explicit_orbit_cutoff": 500,
        "tallies": dict(sorted(tally.items())),
        "first_example_per_exclusion": examples,
        "residual_non_prime_power_orders": residual,
        "warning": "Finite exact evidence with imported published theorems; residual means only these filters did not decide.",
    }


def orbit_examples(qs: list[int]) -> list[dict]:
    results = []
    for q in qs:
        group, complete = generated_multipliers(q)
        assert complete
        orbits = multiplier_orbits(q, group)
        lengths = Counter(map(len, orbits))
        reachable = 1
        for orbit in orbits:
            reachable |= reachable << len(orbit)
        results.append({
            "q": q, "n": q + 1, "v": q * q + q + 1,
            "prime_generators": sorted(factor(q)),
            "multiplier_group_order": len(group),
            "orbit_length_histogram": dict(sorted(lengths.items())),
            "size_q_plus_one_reachable": bool((reachable >> (q + 1)) & 1),
            "orbits": orbits if q <= 12 else None,
        })
    return results


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["small", "filters", "orbits"])
    parser.add_argument("--bound", type=int, default=5000)
    parser.add_argument("--seconds", type=float, default=10)
    parser.add_argument("--max-nodes", type=int, default=2_000_000)
    parser.add_argument("--output-prefix", type=Path, required=True)
    args = parser.parse_args()
    report = {
        "mode": args.mode,
        "recorded_utc": datetime.now(timezone.utc).isoformat(),
        "python": platform.python_version(),
        "dependencies": "Python standard library only",
    }
    if args.mode == "small":
        report["results"] = [direct_search(n, args.seconds, args.max_nodes) for n in (2, 5, 7, 9, 10)]
    elif args.mode == "orbits":
        report["results"] = orbit_examples([4, 6, 8, 9, 10, 12])
    else:
        report["results"] = filters(args.bound)
    encoded = json.dumps(report, indent=2, sort_keys=True) + "\n"
    args.output_prefix.with_suffix(".json").write_text(encoded)
    # The stdout capture is deliberately identical to the JSON report.
    args.output_prefix.with_suffix(".stdout").write_text(encoded)
    print(encoded, end="")


if __name__ == "__main__":
    main()
